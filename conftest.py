@pytest.hookimpl(hookwrapper=True, tryfirst=True)
def pytest_runtest_makereport(item):
    """
    ХУК PYTEST ДЛЯ ПЕРЕХВАТА РЕЗУЛЬТАТОВ ТЕСТА.
    
    Этот хук срабатывает после выполнения каждого теста и сохраняет
    информацию о результате (passed/failed/skipped) в объект теста.
    
    Это необходимо для работы фикстуры page, которая проверяет
    request.node.rep_call.failed для сохранения скриншота.
    
    Args:
        item: объект теста pytest
    """
    outcome = yield
    rep = outcome.get_result()
    setattr(item, "rep_" + rep.when, rep)  # Сохраняем результат в атрибут теста